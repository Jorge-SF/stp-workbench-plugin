using System;
using System.IO;
using Maptek.Vulcan.Stp.Bridge.Json;
using Newtonsoft.Json.Linq;

namespace Maptek.Vulcan.Stp.Bridge.Tests
{
    internal static class TestPaths
    {
        private static readonly Lazy<string> RootLazy = new Lazy<string>(() =>
        {
            var directory = new DirectoryInfo(AppContext.BaseDirectory);
            while (directory != null && !File.Exists(Path.Combine(directory.FullName, "StpWorkbench.sln")))
                directory = directory.Parent;
            return directory?.FullName ?? throw new InvalidOperationException("repository root (StpWorkbench.sln) not found above " + AppContext.BaseDirectory);
        });

        private static readonly Lazy<JObject> VectorsLazy = new Lazy<JObject>(() =>
            (JObject)WireJson.Parse(File.ReadAllBytes(Path.Combine(TestDataDirectory, "python_vectors.json"))));

        public static string RepoRoot => RootLazy.Value;

        public static string GoldenExpected => Path.Combine(RepoRoot, "tools", "golden", "expected");

        public static string GoldenFixtures => Path.Combine(RepoRoot, "tools", "golden", "fixtures");

        public static string TestDataDirectory => Path.Combine(RepoRoot, "src", "StpBridge.Tests", "TestData");

        /// <summary>TestData/python_vectors.json, generated by TestData/make_python_vectors.py.</summary>
        public static JObject PythonVectors => VectorsLazy.Value;
    }
}
